/**
 * Server-generated private storage key, namespaced so a key for one tenant,
 * assignment, enrollment, or submission can never collide with another:
 * `tenants/{tenantId}/assignments/{assignmentId}/{enrollmentId}/{submissionId}.{ext}`.
 * Every segment is a server-derived identifier; the client is never trusted
 * for any part of the key. Returns null when a segment is malformed.
 */
function buildSubmissionStorageKey(context) {
    const segments = [context.tenantId, context.assignmentId, context.enrollmentId, context.submissionId];
    for (const segment of segments) {
        if (typeof segment !== 'string' || !ID_PATTERN.test(segment))
            return null;
    }
    if (typeof context.fileExtension !== 'string' || !EXTENSION_PATTERN.test(context.fileExtension))
        return null;
    const key = `tenants/${segments[0]}/assignments/${segments[1]}/${segments[2]}/${segments[3]}.${context.fileExtension}`;
    if (key.length > exports.MAX_STORAGE_KEY_LENGTH || !STORAGE_KEY_PATTERN.test(key))
        return null;
    return key;
}
/** Whether the submission window is open for this assignment at `now`. */
function evaluateSubmissionWindow(assignment, now) {
    if (assignment.archived)
        return { open: false, reason: 'archived' };
    if (assignment.status !== 'published') {
        return { open: false, reason: assignment.status === 'closed' ? 'closed' : 'not_published' };
    }
    if (!assignment.deadlineUtc)
        return { open: true, late: false };
    const deadline = Date.parse(assignment.deadlineUtc);
    if (!Number.isFinite(deadline))
        return { open: false, reason: 'deadline_passed' };
    if (now.getTime() <= deadline)
        return { open: true, late: false };
    const policy = normalizeLatePolicy(assignment.latePolicy);
    if (policy === 'accept')
        return { open: true, late: false };
    if (policy === 'mark_late')
        return { open: true, late: true };
    return { open: false, reason: 'deadline_passed' };
}
/**
 * How long an unverified `pending_upload` row may stay untouched before it is
 * treated as abandoned. The upload authorization is short-lived (at most 600 s,
 * see `assignment-storage.MAX_UPLOAD_URL_TTL_SECONDS`); this window adds a
 * grace period so a slow but legitimate upload is never reclaimed. A row
 * younger than this is still in flight and keeps counting.
 */
exports.ABANDONED_PENDING_UPLOAD_AFTER_MS = 15 * 60 * 1000;
/**
 * An abandoned upload: a non-revoked row that never had an object verified and
 * whose authorization can no longer be valid. It holds no content, so it must
 * not consume the resubmission/limit budget; the student may resume it (a new
 * upload authorization) or cancel it explicitly at any time.
 *
 * An unknown `submitted_at` is NOT treated as abandoned: without a timestamp
 * the row cannot be proven stale, so it keeps counting (conservative).
 */
function isAbandonedPendingUpload(submission, nowMs, ttlMs = exports.ABANDONED_PENDING_UPLOAD_AFTER_MS) {
    if (submission.status === 'revoked')
        return false;
    if ((submission.fileSizeBytes ?? 0) > 0)
        return false;
    const submittedAtMs = submission.submittedAtMs ?? null;
    if (submittedAtMs === null || !Number.isFinite(submittedAtMs))
        return false;
    return nowMs - submittedAtMs >= ttlMs;
}
/**
 * Whether an enrolled student may submit (or resubmit) right now. A revoked
 * submission is invalidated and never counts toward the resubmission/limit
 * gates, so a teacher revocation re-opens the slot. An abandoned
 * `pending_upload` (see `isAbandonedPendingUpload`) is equally excluded: it
 * carries no verified object, so it can never permanently burn the budget. The
 * next version is `max(version) + 1` over the complete history and is always
 * monotonically increasing.
 */
function evaluateSubmission(assignment, existing, now) {
    const window = evaluateSubmissionWindow(assignment, now);
    if (!window.open) {
        return { allowed: false, reason: window.reason === 'deadline_passed' ? 'DEADLINE_PASSED' : 'NOT_OPEN' };
    }
    const ttlMs = assignment.pendingUploadTtlMs ?? exports.ABANDONED_PENDING_UPLOAD_AFTER_MS;
    const active = existing.filter((submission) => submission.status !== 'revoked'
        && !isAbandonedPendingUpload(submission, now.getTime(), ttlMs));
    if (assignment.resubmissionPolicy === 'block' && active.length > 0) {
        return { allowed: false, reason: 'RESUBMISSION_BLOCKED' };
    }
    if (active.length >= assignment.maxSubmissions) {
        return { allowed: false, reason: 'SUBMISSION_LIMIT_REACHED' };
    }
    const maxVersion = existing.reduce((max, submission) => Math.max(max, Number(submission.version) || 0), 0);
    return { allowed: true, late: window.late, nextVersion: maxVersion + 1 };
}
/**
 * Deny-by-default audience match for a student: the enrollment must be in the
 * same tenant, and must match a branch-, group- or course-scoped assignment.
 * A tenant-wide assignment matches any enrollment in the tenant. A course
 * audience (set and no explicit group) requires the enrollment's group to
 * belong to that course, so students outside the course never see or submit
 * to the assignment.
 */
function enrollmentMatchesAssignment(assignment, enrollment) {
    if (assignment.tenantId !== enrollment.tenantId)
        return false;
    if (assignment.branchScope === 'branch') {
        return assignment.branchId !== null && enrollment.branchId !== null && assignment.branchId === enrollment.branchId;
    }
    if (assignment.groupId !== null) {
        return enrollment.groupId !== null && assignment.groupId === enrollment.groupId;
    }
    if (assignment.courseId !== null) {
        return enrollment.courseId !== null && assignment.courseId === enrollment.courseId;
    }
    return true;
}
