/**
 * Validate the client-declared, purely descriptive part of an upload request
 * (file name, MIME-ish type, allowed extension). The storage identity is
 * server-owned on both values:
 *  - any client-supplied `storage_key` is rejected: it can never reference
 *    this submission because the key is generated below;
 *  - a client-declared `file_size_bytes` is ignored entirely; the
 *    authoritative size is verified server-side (see validateVerifiedUpload).
 * `scan_status` is deliberately not read here either: it is server-owned.
 */
function validateUploadRequest(body, limits) {
    const record = isRecord(body) ? body : {};
    const fileName = typeof record['file_name'] === 'string' ? record['file_name'].trim() : '';
    if (!fileName)
        return { ok: false, error: 'file_name is required' };
    if (fileName.length > exports.MAX_FILE_NAME_LENGTH)
        return { ok: false, error: 'file_name is too long' };
    if (/[\\/]/.test(fileName) || /[\u0000-\u001f]/.test(fileName)) {
        return { ok: false, error: 'file_name must not contain path separators or control characters' };
    }
    const fileType = typeof record['file_type'] === 'string' ? record['file_type'].trim() : '';
    if (!fileType)
        return { ok: false, error: 'file_type is required' };
    if (fileType.length > exports.MAX_FILE_TYPE_LENGTH)
        return { ok: false, error: 'file_type is too long' };
    const extension = extensionOf(fileName);
    if (!extension)
        return { ok: false, error: 'file_name must carry an extension' };
    if (limits.allowedFileTypes.length > 0 && !limits.allowedFileTypes.includes(extension)) {
        return { ok: false, error: 'file type is not allowed for this assignment' };
    }
    if (record['storage_key'] !== undefined && record['storage_key'] !== null && record['storage_key'] !== '') {
        return { ok: false, error: 'storage_key is server-owned and must not be provided' };
    }
    return { ok: true, value: { fileName, fileType, extension } };
}
